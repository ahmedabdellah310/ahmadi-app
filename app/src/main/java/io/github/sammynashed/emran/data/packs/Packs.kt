/** Where a pack is: not there, on its way (bytes so far of the total), or its last try failed. */
sealed class PackStatus {
    object Idle : PackStatus()
    data class Downloading(val done: Long, val total: Long) : PackStatus()
    data class Failed(val reason: String) : PackStatus()
}

/**
 * Emran's optional downloads ("packs"): the Hifz check, the hadith books, the video backgrounds.
 *
 * They are kept out of the APK so the app stays small, and Emran handles them itself: one tap downloads, checks the
 * sha256 of every file and puts it where the app reads it. A pack lives in the app's private storage, which an
 * update never touches (only the user deleting it, here or in Android's settings, removes it), so nobody downloads
 * anything twice after updating.
 *
 * Hosting: <base>/<pack>/[<abi>/]<file>[.N] on GitHub Pages (repo SammyNashed/emran-packs), with jsDelivr as the backup.
 * Files are cut in 4 MiB parts (.0, .1, ...) which are joined here. Sizes, hashes and part counts are compiled
 * in ([PackCatalog], generated by ~/emran-release/build-packs.py), so a swapped file on the server is refused.
 */
object Packs {
    /**
     * Where the packs live. jsDelivr refuses a GitHub repo over 50 MB, and the packs are ~78 MB, so there is no
     * backup mirror yet; the sha256 check still protects every download.
     */
    private val BASES = emptyList<String>()
    private const val PART = 4L * 1024 * 1024

    class Def(
        val id: String,
        val ar: String,
        val en: String,
        val descAr: String,
        val descEn: String,
        /** Where its files go; hadith books go where the Hadith reader already looks. */
        val dir: (Context) -> File,
    ) {
        fun name(ar: Boolean) = if (ar) this.ar else en
        fun desc(ar: Boolean) = if (ar) descAr else descEn
    }

    private fun under(name: String): (Context) -> File = { File(it.filesDir, "packs/$name") }

    val DEFS: List<Def> = listOf(
        Def("hifz", "فحص الحفظ", "Hifz check",
            "يستمع إلى تلاوتك ويصحّحها كلمة بكلمة، دون إنترنت", "Listens to your recitation and checks it word by word, offline", under("hifz")),
        Def("hadith-bukhari", "صحيح البخاري", "Sahih al-Bukhari", "كتاب الحديث", "Hadith book", { File(it.filesDir, "hadith") }),
        Def("hadith-muslim", "صحيح مسلم", "Sahih Muslim", "كتاب الحديث", "Hadith book", { File(it.filesDir, "hadith") }),
        Def("hadith-abudawud", "مختارات من سنن أبي داود", "Selections from Sunan Abi Dawud", "كتاب الحديث", "Hadith book", { File(it.filesDir, "hadith") }),
        Def("hadith-tirmidhi", "مختارات من جامع الترمذي", "Selections from Jami at-Tirmidhi", "كتاب الحديث", "Hadith book", { File(it.filesDir, "hadith") }),
        Def("hadith-nasai", "مختارات من سنن النسائي", "Selections from Sunan an-Nasa'i", "كتاب الحديث", "Hadith book", { File(it.filesDir, "hadith") }),
        Def("hadith-ibnmajah", "مختارات من سنن ابن ماجه", "Selections from Sunan Ibn Majah", "كتاب الحديث", "Hadith book", { File(it.filesDir, "hadith") }),
        Def("tafsir-muyassar", "التفسير الميسر", "Tafsir Al-Muyassar", "تفسير عربي ميسّر وموجز", "A short, simple Arabic tafsir", { File(it.filesDir, "tafsir/muyassar") }),
        Def("tafsir-saadi", "تفسير السعدي", "Tafsir As-Sa'di", "تفسير عربي مفصّل للسعدي", "As-Sa'di's Arabic tafsir", { File(it.filesDir, "tafsir/saadi") }),
        Def("tafsir-jalalayn-ar", "تفسير الجلالين", "Tafsir Al-Jalalayn", "تفسير عربي مختصر", "A concise Arabic tafsir", { File(it.filesDir, "tafsir/jalalayn-ar") }),
        Def("video-bg", "خلفيات الفيديو", "Video backgrounds",
            "مقاطع طبيعة هادئة لفيديوهات الآيات", "Calm nature clips for ayah videos", under("video-bg")),
    )

    fun def(id: String) = DEFS.firstOrNull { it.id == id }

    /** The phone's own CPU flavour, among the two Emran ships. */
    val abi: String = Build.SUPPORTED_ABIS.firstOrNull { it == "arm64-v8a" || it == "armeabi-v7a" } ?: "arm64-v8a"

    /** What this pack needs on THIS phone: its catalog rows, each with where it is stored. */
    private fun files(context: Context, id: String): List<Pair<PackCatalog.Row, File>> {
        val d = def(id) ?: return emptyList()
        val dir = d.dir(context)
        return PackCatalog.ROWS.filter { it.pack == id && (it.abi == null || (it.abi == abi && NATIVE_FROM_PACK)) }
            .map { it to if (it.abi != null) File(dir, "lib/${it.name}") else File(dir, it.name) }
    }

    /**
     * Whether the onnxruntime native library comes with the Hifz pack. The Telegram ("full") build leaves it out of
     * the APK to stay small; the F-Droid build keeps it inside (F-Droid does not allow fetching executable code).
     */
    private val NATIVE_FROM_PACK get() = BuildConfig.SELF_UPDATE

    fun totalBytes(id: String): Long = PackCatalog.ROWS.filter { it.pack == id && (it.abi == null || (it.abi == abi && NATIVE_FROM_PACK)) }.sumOf { it.size }

    // ------------------------------------------------------------------ state

    private val scope = CoroutineScope(SupervisorJob() + Dispatchers.IO)
    private val jobs = HashMap<String, Job>()
    private val _status = MutableStateFlow<Map<String, PackStatus>>(emptyMap())
    val status: StateFlow<Map<String, PackStatus>> = _status.asStateFlow()

    /** Bumped when something is installed or deleted, so screens re-read [isInstalled]. */
    private val _changes = MutableStateFlow(0)
    val changes: StateFlow<Int> = _changes.asStateFlow()

    private fun set(id: String, s: PackStatus) { _status.value = _status.value + (id to s) }

    /** A tafsir edition comes as one zip that is unpacked into its folder; a marker file says it is whole. */
    private fun isZipPack(id: String) = PackCatalog.ROWS.any { it.pack == id && it.name.endsWith(".zip") }
    private fun marker(context: Context, id: String) = File(def(id)!!.dir(context), ".ok")

    fun isInstalled(context: Context, id: String): Boolean {
        if (id == "hifz") adoptOldModel(context)
        if (isZipPack(id)) return marker(context, id).isFile && File(def(id)!!.dir(context), "meta.json").isFile
        val f = files(context, id)
        return f.isNotEmpty() && f.all { (r, file) -> file.isFile && file.length() == r.size }
    }

    /** Bytes the pack takes on the phone now (0 when absent). */
    fun sizeOnDisk(context: Context, id: String): Long =
        if (isZipPack(id)) def(id)!!.dir(context).walkTopDown().filter { it.isFile }.sumOf { it.length() }
        else files(context, id).sumOf { (_, f) -> if (f.isFile) f.length() else 0L }

    /** When it was put there, for "recently downloaded" ordering. */
    fun installedAt(context: Context, id: String): Long =
        if (isZipPack(id)) marker(context, id).lastModified()
        else files(context, id).maxOfOrNull { (_, f) -> f.lastModified() } ?: 0L

    /**
     * Anyone who already used Hifz in an earlier Emran has the model in `files/ratl-model/`. It moves into the pack
     * (a rename on the same disk, no copy, no download) so they only fetch what is new for them.
     */
    private fun adoptOldModel(context: Context) {
        val row = PackCatalog.ROWS.firstOrNull { it.pack == "hifz" && it.abi == null } ?: return
        val dest = File(def("hifz")!!.dir(context), row.name)
        if (dest.isFile) return
        val old = File(context.filesDir, "ratl-model/${row.name}")
        if (old.isFile && old.length() == row.size) {
            dest.parentFile?.mkdirs()
            if (old.renameTo(dest)) File(context.filesDir, "ratl-model/vocab.json").let { v -> if (v.isFile) v.renameTo(File(dest.parentFile, "vocab.json")) }
        }
    }

    // ------------------------------------------------------------------ download

    fun start(context: Context, id: String) {
        val app = context.applicationContext
        synchronized(jobs) {
            if (jobs[id]?.isActive == true) return
            set(id, PackStatus.Downloading(0, totalBytes(id)))
            jobs[id] = scope.launch { download(app, id) }
        }
    }

    fun cancel(id: String) {
        synchronized(jobs) { jobs.remove(id)?.cancel() }
        set(id, PackStatus.Idle)
    }

    private suspend fun download(context: Context, id: String) {
        try {
            val list = files(context, id)
            val total = list.sumOf { it.first.size }
            var base = 0L
            for ((row, file) in list) {
                coroutineContext.ensureActive()
                if (row.name.endsWith(".zip")) {
                    if (!isInstalled(context, id)) {
                        fetch(context, row, file) { done -> set(id, PackStatus.Downloading(base + done, total)) }
                        unpackTafsir(context, id, file)
                    }
                } else if (!(file.isFile && file.length() == row.size)) {
                    fetch(context, row, file) { done -> set(id, PackStatus.Downloading(base + done, total)) }
                }
                base += row.size
                set(id, PackStatus.Downloading(base, total))
            }
            set(id, PackStatus.Idle)
            _changes.value++
            if (isZipPack(id)) io.github.sammynashed.emran.data.TafsirLibrary.version.intValue++
        } catch (e: CancellationException) {
            set(id, PackStatus.Idle)
            throw e
        } catch (e: Exception) {
            set(id, PackStatus.Failed(e.message ?: e.javaClass.simpleName))
        }
    }

    /** Unpacks a tafsir zip (only meta.json and <n>.json, so a hostile file cannot write elsewhere), then marks it whole. */
    private fun unpackTafsir(context: Context, id: String, zip: File) {
        val dir = def(id)!!.dir(context)
        val name = Regex("""\d{1,3}\.json""")
        java.util.zip.ZipInputStream(zip.inputStream().buffered()).use { z ->
            while (true) {
                val e = z.nextEntry ?: break
                val n = e.name.substringAfterLast('/')
                if (e.isDirectory || !(n == "meta.json" || name.matches(n))) continue
                val tmp = File(dir, "$n.tmp")
                tmp.outputStream().use { o -> z.copyTo(o) }
                tmp.renameTo(File(dir, n))
            }
        }
        zip.delete()
        check(File(dir, "meta.json").isFile && File(dir, "114.json").isFile) { "the tafsir file is incomplete" }
        File(dir, ".ok").writeText("1")
    }

    /** The pack files ship inside the APK (assets/packs): "installing" copies them out, checks the sha256, no network. */
    private suspend fun fetch(context: Context, row: PackCatalog.Row, target: File, progress: (Long) -> Unit) = withContext(Dispatchers.IO) {
        target.parentFile?.mkdirs()
        val tmp = File(target.path + ".part")
        tmp.delete()
        var have = 0L
        context.assets.open("packs/" + row.pack + "/" + row.name).use { input ->
            tmp.outputStream().use { out ->
                val buf = ByteArray(64 * 1024)
                while (true) {
                    val n = input.read(buf); if (n < 0) break
                    out.write(buf, 0, n); have += n; progress(have)
                }
            }
        }
        if (tmp.length() != row.size) { tmp.delete(); throw IOException("size ${tmp.length()} != ${row.size}") }
        if (sha256(tmp) != row.sha256) { tmp.delete(); throw IOException("the file did not match what was expected") }
        if (target.exists()) target.delete()
        if (!tmp.renameTo(target)) throw IOException("could not store the file")
        target.setReadOnly()
    }

    private fun url(row: PackCatalog.Row, i: Int, base: String): String =
        base + row.pack + "/" + (if (row.abi != null) row.abi + "/" else "") + row.name + (if (row.parts > 1) ".$i" else "")

    /** One file: its parts joined into `<file>.part` (resumable), checked against the catalog's sha256, then renamed. */
    private suspend fun fetch(row: PackCatalog.Row, target: File, id: String, progress: (Long) -> Unit) {
        target.parentFile?.mkdirs()
        val tmp = File(target.path + ".part")
        var last: Exception? = null
        for (attempt in 0 until 4) {
            if (attempt > 0) delay(1_500L * attempt)
            try {
                var have = if (tmp.exists()) tmp.length().coerceAtMost(row.size) else 0L
                if (have == row.size) { /* all there: only the check is left */ } else {
                    var i = (have / PART).toInt()
                    var inPart = have % PART
                    while (i < row.parts) {
                        val ok = fetchPart(url(row, i, BASES[attempt % BASES.size]), tmp, inPart, append = i > 0 || inPart > 0) { n -> have += n; progress(have) }
                        if (!ok) { have = 0; i = 0; inPart = 0; tmp.delete(); progress(0); continue } // server ignored Range: start over
                        i++; inPart = 0
                    }
                }
                if (tmp.length() != row.size) throw IOException("size ${tmp.length()} != ${row.size}")
                if (sha256(tmp) != row.sha256) { tmp.delete(); throw IOException("the file did not match what was expected") }
                if (target.exists()) target.delete()
                if (!tmp.renameTo(target)) throw IOException("could not store the file")
                target.setReadOnly() // native libraries must not be writable to be loaded (Android 14+)
                return
            } catch (e: CancellationException) {
                throw e
            } catch (e: IOException) {
                last = e
            }
        }
        throw last ?: IOException("download failed")
    }

    /** Appends one part to [tmp], from byte [from] of that part. False when the server answered a Range with the whole file. */
    private suspend fun fetchPart(url: String, tmp: File, from: Long, append: Boolean, onBytes: (Int) -> Unit): Boolean = withContext(Dispatchers.IO) {
        io.github.sammynashed.emran.data.NoRemote.block()
        @Suppress("UNREACHABLE_CODE")
        val c = URL(url).openConnection() as HttpURLConnection
        try {
            c.connectTimeout = 20_000; c.readTimeout = 25_000; c.instanceFollowRedirects = true
            if (from > 0) c.setRequestProperty("Range", "bytes=$from-")
            val code = c.responseCode
            if (code == 200 && from > 0) return@withContext false
            if (code != 200 && code != 206) throw IOException("server answered $code")
            java.io.FileOutputStream(tmp, append).use { out ->
                val buf = ByteArray(64 * 1024)
                c.inputStream.use { input ->
                    while (true) {
                        val n = input.read(buf)
                        if (n < 0) break
                        out.write(buf, 0, n)
                        onBytes(n)
                        if (!isActive) throw CancellationException()
                    }
                }
            }
            true
        } finally { c.disconnect() }
    }

    private fun sha256(f: File): String {
        val d = MessageDigest.getInstance("SHA-256")
        f.inputStream().use { i -> val b = ByteArray(1 shl 16); while (true) { val n = i.read(b); if (n < 0) break; d.update(b, 0, n) } }
        return d.digest().joinToString("") { "%02x".format(it) }
    }

    // ------------------------------------------------------------------ delete

    /** Removes a pack's files (only ever on the user's say-so, from the Storage page). */
    fun delete(context: Context, id: String) {
        cancel(id)
        if (isZipPack(id)) {
            def(id)!!.dir(context).deleteRecursively()
            io.github.sammynashed.emran.data.TafsirLibrary.version.intValue++
            _changes.value++
            return
        }
        files(context, id).forEach { (_, f) -> f.setWritable(true); f.delete(); File(f.path + ".part").delete() }
        _changes.value++
    }

    // ------------------------------------------------------------------ Hifz's native library

    /**
     * Points onnxruntime at the library inside the Hifz pack. Must run before the first use of onnxruntime. A build
     * that carries the library itself (F-Droid) needs nothing. Returns false when the library is not there yet.
     */
    fun prepareNative(context: Context): Boolean {
        if (!NATIVE_FROM_PACK) return true
        val dir = File(def("hifz")!!.dir(context), "lib")
        val ok = files(context, "hifz").filter { it.first.abi != null }.all { (r, f) -> f.isFile && f.length() == r.size }
        if (ok) System.setProperty("onnxruntime.native.path", dir.path)
        return ok
    }

    /** The folder the Hifz engine reads its model (and vocab) from. */
    fun hifzModelDir(context: Context): File = def("hifz")!!.dir(context)
}
